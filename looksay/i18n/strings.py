def tr(key: str, lang: str = "en", **fmt) -> str:
    entry = STRINGS.get(key)
    if entry is None:
        return key
    try:
        text = entry[LANGUAGES.index(lang)]
    except ValueError:
        text = entry[0]
    return text.format(**fmt) if fmt else text
